namespace ElasticDesktopManager.Core.I18n;

/// <summary>
/// 轻量国际化：zh_CN（默认）与 en 两套词典。
/// 取值顺序：当前语言词典 → zh_CN → 原始 key。
/// </summary>
public static class Localization
{
    public static string Current { get; private set; } = "zh_CN";
    public static event Action? LanguageChanged;

    public static void SetLanguage(string lang)
    {
        lang = lang is "zh_CN" or "en" ? lang : "zh_CN";
        if (Current == lang) return;
        Current = lang;
        LanguageChanged?.Invoke();
    }

    public static string L(string key)
    {
        if (Current == "en" && En.TryGetValue(key, out var en) && !string.IsNullOrEmpty(en))
            return en;
        if (Zh.TryGetValue(key, out var zh) && !string.IsNullOrEmpty(zh))
            return zh;
        return key;
    }

    public static string L(string key, params object[] args)
    {
        string fmt = L(key);
        try { return string.Format(fmt, args); }
        catch (FormatException) { return fmt; }
    }

